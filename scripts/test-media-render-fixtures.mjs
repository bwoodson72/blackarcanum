function crc32(buffer) {
  let crc = -1;
  for (const byte of buffer) {
    crc ^= byte;
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
  }
  return (crc ^ -1) >>> 0;
}
function chunk(type, payload) {
  const id = Buffer.from(type, "ascii");
  const size = Buffer.alloc(4);
  size.writeUInt32BE(payload.length);
  const checksum = Buffer.alloc(4);
  checksum.writeUInt32BE(crc32(Buffer.concat([id, payload])));
  return Buffer.concat([size, id, payload, checksum]);
}
function blankPng(width, height) {
  const head = Buffer.from("89504e470d0a1a0a", "hex");
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // RGB samples: 8-bit depth, type 2, no alpha.
  ihdr[9] = 2;
  const rowSize = width * 3 + 1;
  const pixels = Buffer.alloc(rowSize * height, 0); // filter=0, pure black test only
  return Buffer.concat([
    head,
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(pixels, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
