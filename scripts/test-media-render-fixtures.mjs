function build() {
  fs.rmSync("dist", { recursive: true, force: true });
  fs.rmSync(".astro", { recursive: true, force: true });
  return spawnSync("npm", ["run", "build"], {
    cwd: root, encoding: "utf8", timeout: 180000,
  });
}
function renderBlock(html, variant, occurrence = 0) {
  const regex = new RegExp('<div\\b[^>]*data-media-variant="' + variant +
    '"[^>]*>([\\s\\S]*?)<\\/div>', "g");
  const matches = [...html.matchAll(regex)];
  assert.ok(matches.length > occurrence, "Missing rendered " + variant + " variant #" + occurrence);
  return matches[occurrence][1];
}
function imgTag(block) {
  const tag = block.match(/<img\b[^>]*>/);
  assert.ok(tag, "MediaImage must include a semantic image element");
  return tag[0];
}
function attr(html, name) {
  const match = html.match(new RegExp('(?:^|\\s)' + name + '="([^"]*)"'));
  return match?.[1] ?? null;
}
function hasResponsiveWidths(block) {
  const values = [...block.matchAll(/\s(\d+)w(?=[,"])/g)].map((m) => Number(m[1]));
  assert.ok(values.length >= 2 && new Set(values).size >= 2,
    "Raster images must emit several distinct intrinsic width candidates");
}

